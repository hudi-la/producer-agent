// 「边想边出的字」里，哪些该给人看。
//
// 判据跟 brain/reply.js 的 foldReply 是同一条：**动工具之前说的话都是工作稿**。
// 它要去查资料，说明还没想完；想完了才不用再动工具。
//
// 落库那头已经按这条切了。但屏幕上还是会滚过去——因为预览是照单全收的，
// 于是查一次资料就闪一行英文（"I'll start by loading the web tools."），
// 一轮查十几次就闪十几次。这个文件治的是屏幕。
//
// 两条规矩：
//
// 1. **动工具 = 刚才那些字作废。** 收到 tool 事件就把已经画出来的抹掉。
//    这条是确定的，不猜。
//
// 2. **动过工具之后，新的字先按住 HOLD 毫秒再画。** 光靠第 1 条不够：
//    开场白那行字是一个字一个字流出来的，画出来 0.3 秒之后才等到 tool 事件，
//    人眼已经看见了。按住之后它在被画出来之前就作废了，一眼都看不到。
//
//    只在**动过工具之后**才按——普通对话（不查资料的那种）第一个字照旧
//    立刻上屏，一毫秒都不耽误。而查资料那一轮本来就要等几十秒，
//    半秒钟看不出来。「首字多久到」是这条路唯一要紧的指标，不能为了
//    治闪把它整个赔进去。
//
// 治不了的一种：它中途写了一整段**长**英文中间报告（几秒钟的量）。
// 那种按不住，会先画出来、下次动工具时再被抹掉。这是这条路的上限——
// 要一个字都不漏，只能等它彻底想完再画，那就等于没有边想边出字。

/** 动过工具之后，新的一段字按住多久才上屏。 */
export const HOLD_MS = 500

export const liveInit = () => ({
  text: '',      // 该画在屏幕上的
  pend: '',      // 按住还没画的
  since: 0,      // 这一段是什么时候开始按住的
  open: true,    // true = 直接画（还没动过工具，或者这一段已经熬过 HOLD）
})

/**
 * 收一个事件，返回新状态。纯函数，不碰 DOM 也不看时钟——now 由调用方给，
 * 这样它才测得了。
 */
export function liveStep(s, e, now = 0) {
  if (e?.t === 'delta') {
    if (!e.text) return s
    if (s.open) return { ...s, text: s.text + e.text }
    const since = s.since || now
    const pend = s.pend + e.text
    // 熬过 HOLD 还没被工具打断 = 这段不是开场白，放行，之后这一段就直接画
    if (now - since >= HOLD_MS) return { text: s.text + pend, pend: '', since: 0, open: true }
    return { ...s, pend, since }
  }
  // 动工具：刚才说的那些是工作稿，作废。已经画出来的也抹掉。
  if (e?.t === 'tool') return { text: '', pend: '', since: 0, open: false }
  return s
}

/**
 * 边想边出字时，末尾那行机器读的记号不上屏。
 *
 * 它是一个字一个字流出来的，所以**流到一半也得挡**——不挡的话你会先看见
 * 「[[LET」「[[LETTER]] {"to":"a@」这种半截东西在屏幕上长出来，
 * 想完之后又忽然消失，看起来像出了什么毛病。
 *
 * 只咬末尾、且必须是 `[[大写字母` 那一串：
 *   · 正文里的 [1]、[链接](…) 碰不着（没有连着两个方括号）
 *   · markdown 的 [[某某]] 双链也碰不着（里面不是大写字母，而且它后面还有正文）
 *
 * [[LETTER]] 和 [[FACTS]] 都归它管——两条路的末尾贴的是同一类东西。
 */
export const stripTag = (t) =>
  String(t ?? '').replace(/\n*\[\[[A-Z]*(?:\]\][\s\S]*)?$/, '').trimEnd()
