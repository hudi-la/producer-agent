// 待处理 / 等回复 —— **你自己点的标签**。
//
// 原来这是系统算的：Fairwind 贴一个，你改掉之后「管到下一件真事发生为止
// （新的对外通信、跟进日到期），之后 Fairwind 重新接管」。
// 那条规则的意思是：**你的判断会被系统悄悄改回去，而你不会收到通知。**
//
// 现在不了。标签就是标签：你点了「等回复」它就是等回复，直到你自己再点。
// 库里 ball_eff 已经直接等于 p.ball（0058），这儿只是照读。
//
// 三态：待处理 / 等回复 / 一个都不点。点已经亮着的那个 = 灭掉。
import { t } from '../i18n/index.js'

export const BALL_LABEL = { me: t('待处理'), them: t('等回复') }

/** 界面上摆出来的两个标，顺序固定。 */
export const BALL_STATES = [['me', BALL_LABEL.me], ['them', BALL_LABEL.them]]

/** 你点的是哪个。null = 一个都没点。 */
export function ballOf(p) {
  return p.ball_eff || null
}

