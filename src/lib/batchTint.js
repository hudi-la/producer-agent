// 哪几张卡该偏一点色。
//
// 规矩就一条：**一叠一个色**。
//
// 一叠 = 一次造卡任务撒出去的一批（找 workshop 机构 · 树皮书 / · 媒体艺术AI /
// 找模特经纪 / 聚合源 scout）。这种批里的卡标题长得几乎一样，摊在板上
// 分不清谁是哪一摊的；折起来的时候你看见的更只是一张叠头。给每摊一点底色，
// 一眼就分开了。
//
// **不成摊的不上色**：你手填的、机构监测抓的那些正经机会，一张卡一件事，
// 自己站得住，保持原样。
//
// （最早写成「只有 kind=workshop 才上色」，漏了模特经纪那一叠 —— 上色跟
// 这批东西是什么类别无关，只跟「它是不是一摊里的」有关。）

/**
 * 是不是「一摊里的」。**叠不叠、上不上色，都问这一句** —— 一个判断管两件事，
 * 不会出现「散着铺开却带着摊色」那种自相矛盾的样子。
 *
 * 两个条件：
 *   出自某次造卡任务（散卡不成摊）
 *   而且不是聚合源捞来的
 *
 * 聚合源为什么不算：那一批是从聚合站上捞回来的一堆**各不相同的机会**
 * （驻留、fellowship、开放征集……各是各的），只是碰巧同一次任务捞的。
 * 而树皮书 / 媒体艺术 / 模特经纪那几摊是**朝一批机构撒同一封冷邮件**，
 * 卡的标题几乎一模一样（「工作坊提案 · 某某机构」），不折起来看板就被它们淹了。
 * 前者每张都值得单独站着，后者才需要「这儿是一摞」。
 *
 * 不用「张数少就不算」那种判法：聚合源 11 张其实比模特经纪 7 张还多，
 * 数字分不开这两者 —— 分开它们的是「这批卡彼此像不像」。
 */
// 「scout_」开头的来源都是联网捞回来的各不相同的机会（聚合源那条、Open Call 那条），
// 一律散着铺。判前缀不判具体值：再加一条 scout 任务不用回来改这儿。
const 是一摊里的 = (p) => Boolean(p?.task_id) && !String(p?.source || '').startsWith('scout_')

/** 给看板用：这张卡该不该跟同任务的折成一叠。跟上色是同一个判断。 */
export const inBatch = 是一摊里的

/** 有几号色可用。今天四摊，留两个富余；摊多过这个数就绕回来，
 *  两摊撞色总比没色好。 */
export const SLOTS = 6

/**
 * 算出「哪个任务用几号色」。
 *
 * 按 task_id 排序发号，不按 hash：hash 会让两摊有 1/4 的概率撞到同一号，
 * 而这个功能的全部意义就是把两摊分开。排序发号则保证只要摊数不超过 SLOTS，
 * 每摊必不同色；而且顺序只跟 id 有关，刷新、换机器都是同一个色。
 */
export function tintSlots(pursuits) {
  const tasks = [...new Set((pursuits || []).filter(是一摊里的).map((p) => p.task_id))].sort()
  return new Map(tasks.map((id, i) => [id, i % SLOTS]))
}

/** 这张卡用几号色。不上色的返回 null。 */
export function slotOf(p, slots) {
  if (!p || !slots || !是一摊里的(p)) return null
  const s = slots.get(p.task_id)
  return s === undefined ? null : s
}
