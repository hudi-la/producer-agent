// 库里的文字都是 markdown。发出去之前得渲一遍。
//
// ══ 为什么这一步不能省 ════════════════════════════════════════
// Md.jsx 那条注释记着一次事故：同一份内容在机会线上是粗体，在名片上是四个
// 星号明晃晃摆着——「同一份内容两个样子，而且丑的那个看起来像坏了」。
//
// 只发纯文本，就是把那次事故复现到**收件人的信箱里**。区别是这一次，
// 那份丑的你看不见，也改不回来。
//
// ══ 两条语义必须跟前端对齐 ════════════════════════════════════
//   gfm    —— 列表、自动链接        （前端的 remark-gfm）
//   breaks —— 单个换行就换行        （前端的 remark-breaks）
// 不对齐的话，你在屏幕上校对的那一版和对方收到的那一版是两个东西，
// 而你只看得见前一版。
//
// 用 marked 而不是搬一整套 remark：remark 那套要六个包，换来的差别在这几种
// 构造（粗体、列表、链接、换行）上看不出来。要是哪天真出现了看得出来的差别，
// 判据就在这个文件的测试里，换回 remark 也有尺子。
import { marked } from 'marked'

marked.setOptions({ gfm: true, breaks: true, async: false })

/**
 * 一份正文的两个身体。
 *
 * text 那份**原样留着 markdown**，不做任何降级处理——纯文本客户端里
 * `**这样**` 读得懂，硬把星号删掉反而丢了强调。
 */
export function renderBody(md) {
  const text = String(md ?? '')
  return { text, html: text ? marked.parse(text) : '' }
}
